import pandas as pd
import streamlit as st
import plotly.express as px
import psycopg
from streamlit.errors import StreamlitSecretNotFoundError

REQUIRED_TABLES = ("jobs", "skills", "job_skills")


class MissingDatabaseTablesError(RuntimeError):
    def __init__(self, database: str, schema: str, missing_tables: list[str]):
        missing = ", ".join(missing_tables)
        super().__init__(
            f"Database '{database}', schema '{schema}' is missing: {missing}. "
            "Run src/schema.sql against this exact database, then refresh."
        )


st.set_page_config(
    page_title="Job Market Skills Tracker",
    page_icon="📊",
    layout="wide"
)

st.title("📊 Job Market Skills Tracker")
st.caption("Explore detected skills in Data Engineer job postings")

def get_connection():
    try:
        database_url = st.secrets["DATABASE_URL"]
    except (StreamlitSecretNotFoundError, KeyError):
        st.error(
            "The DATABASE_URL secret is missing. Add it to the app's "
            "Streamlit secrets, then redeploy."
        )
        st.stop()

    return psycopg.connect(
        database_url,
        connect_timeout=10
    )


@st.cache_data(ttl=60)
def load_data():
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("CREATE SCHEMA IF NOT EXISTS public;")
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS public.jobs (
                    job_id TEXT PRIMARY KEY,
                    title TEXT,
                    company TEXT,
                    location TEXT,
                    description TEXT,
                    created_at TIMESTAMPTZ,
                    job_url TEXT,
                    raw_data JSONB,
                    collected_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                );
                """
            )
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS public.skills (
                    skill_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    skill_name TEXT NOT NULL UNIQUE
                );
                """
            )
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS public.job_skills (
                    job_id TEXT NOT NULL
                        REFERENCES public.jobs (job_id) ON DELETE CASCADE,
                    skill_id INTEGER NOT NULL
                        REFERENCES public.skills (skill_id) ON DELETE CASCADE,
                    PRIMARY KEY (job_id, skill_id)
                );
                """
            )

            cur.execute(
                """
                SELECT current_database(),
                       COALESCE(current_schema(), 'no active schema');
                """
            )
            connection_info = cur.fetchone()
            if connection_info is None:
                raise RuntimeError("Could not identify the connected database.")
            database, schema = connection_info

            cur.execute(
                """
                SELECT table_name
                FROM unnest(%s::text[]) AS table_name
                WHERE to_regclass('public.' || table_name) IS NULL;
                """,
                (list(REQUIRED_TABLES),),
            )
            missing_tables = [row[0] for row in cur.fetchall()]
            if missing_tables:
                raise MissingDatabaseTablesError(
                    database,
                    schema,
                    missing_tables,
                )

            cur.execute("SELECT COUNT(*) FROM public.jobs;")
            jobs_result = cur.fetchone()
            if jobs_result is None:
                raise RuntimeError("The jobs count query returned no result.")
            total_jobs = jobs_result[0]

            cur.execute("SELECT COUNT(*) FROM public.skills;")
            skills_result = cur.fetchone()
            if skills_result is None:
                raise RuntimeError("The skills count query returned no result.")
            total_skills = skills_result[0]

        summary = pd.read_sql("""
            SELECT
                s.skill_name AS skill,
                COUNT(DISTINCT js.job_id) AS job_count
            FROM public.skills s
            JOIN public.job_skills js
                ON s.skill_id = js.skill_id
            GROUP BY s.skill_name
            ORDER BY job_count DESC, s.skill_name;
        """, conn)

    if total_jobs:
        summary["percentage"] = (
            summary["job_count"] / total_jobs * 100
        ).round(1)
    else:
        summary["percentage"] = 0.0

    return total_jobs, total_skills, summary


try:
    total_jobs, total_skills, summary = load_data()

    total_relationships = int(summary["job_count"].sum())

    col1, col2, col3 = st.columns(3)

    col1.metric("Total Jobs", total_jobs)
    col2.metric("Unique Skills", total_skills)
    col3.metric("Skill Relationships", total_relationships)

    st.subheader("Top Demanded Skills")

    top_skills = summary.head(10)

    if not top_skills.empty:
        chart_data = top_skills.sort_values("job_count")

        fig = px.bar(
            chart_data,
            x="job_count",
            y="skill",
            orientation="h",
            text="job_count",
            labels={
                "job_count": "Number of Jobs",
                "skill": "Skill"
            },
            title="Skills by Number of Job Postings"
        )

        fig.update_layout(yaxis_title=None)

        st.plotly_chart(
            fig,
            width="stretch"
        )
    else:
        st.info("No detected skills are available yet.")

    st.subheader("Skill Summary")

    st.dataframe(
        summary,
        width="stretch",
        hide_index=True
    )

except MissingDatabaseTablesError as error:
    st.error(str(error))
    st.info(
        "Check the database name and schema above against the database "
        "where you ran the schema. DATABASE_URL is not shown."
    )
except psycopg.errors.UndefinedTable as error:
    st.error("A required database table could not be found.")
    st.exception(error)
except psycopg.errors.InsufficientPrivilege as error:
    st.error(
        "The database user cannot create or read the dashboard tables. "
        "Use an owner-level DATABASE_URL, or run src/schema.sql as the "
        "database owner."
    )
    st.exception(error)
except psycopg.OperationalError as error:
    st.error(
        "Unable to connect to the database. Verify DATABASE_URL, the "
        "database's availability, network access, and permission to create "
        "tables."
    )
    st.exception(error)
except psycopg.Error as error:
    st.error("The database rejected a dashboard query.")
    st.exception(error)
